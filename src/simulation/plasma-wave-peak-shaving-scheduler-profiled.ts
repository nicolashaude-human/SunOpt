/*
 * ==================================================================
 * ONE RESULT POINT
 * ==================================================================
 *
 * One point of the theoretical 48 h Waterline schedule.
 *
 * IMPORTANT:
 *
 * Only schedule[0] is actually executed.
 *
 * Fifteen minutes later the complete 48 h horizon is shifted
 * forward and calculated again.
 *
 * This is therefore a receding-horizon controller.
 */
export interface PlasmaWavePeakShavingSchedulePoint {

  timestamp: string;

  /*
   * Total PV power.
   *
   * Unit:
   * kW_el
   */
  pvPower: number;

  /*
   * PV remaining after the household reservation.
   *
   * P_export =
   *   max(0, P_PV - P_household)
   *
   * Unit:
   * kW_el
   */
  exportPowerBeforeHeatPump: number;

  /*
   * Forecast HP electrical power selected by Waterline.
   *
   * Unit:
   * kW_el
   */
  scheduledHeatPumpElectricalPower: number;

  /*
   * Thermal equivalent of the scheduled HP power.
   *
   * P_th = P_el * COP
   *
   * Unit:
   * kW_th
   */
  scheduledHeatPumpThermalPower: number;

  /*
   * Remaining PV export after forecast HP operation.
   *
   * Unit:
   * kW_el
   */
  exportPowerAfterHeatPump: number;
}


/*
 * ==================================================================
 * SCHEDULER INPUT
 * ==================================================================
 */
export interface PlasmaWavePeakShavingScheduleInput {

  weatherData: WeatherData;

  heatPump: HeatPump;

  storage: ThermalStorage;

  /*
   * Current position inside the annual 15-minute arrays.
   */
  currentIndex: number;

  /*
   * Storage energy available NOW.
   *
   * In the Plasma-Wave controller this already includes any
   * mandatory reserve restoration belonging to the current step.
   *
   * Unit:
   * kWh_th above storage.minTemperature
   */
  currentStorageEnergy: number;

  /*
   * Total desired 48 h thermal inventory.
   *
   * This remains useful for the normal Waterline energy target.
   *
   * Unit:
   * kWh_th
   */
  requiredThermalInventory: number;

  /*
   * Complete annual array of forecast demand buckets.
   *
   * Entry N belongs to the same index N in weatherData.
   *
   * For the normal configuration:
   *
   *   48 h / 0.25 h = 192 future buckets
   *
   * Each bucket is already generated by the Plasma-Wave
   * all-packages forecast, so its existing safety factor is
   * preserved.
   *
   * Cooling losses are NOT included here.
   *
   * Cooling is calculated separately with the canonical
   * storage model while we walk through the future.
   *
   * Unit:
   * kWh_th per time step
   */
  historicalSeries:
  PlasmaWaveHistoricalSeries;

  /*
   * Storage level below which the common controller would start
   * mandatory reserve charging.
   *
   * Our causal Waterline tries to stay above this value whenever
   * forecast PV makes that physically possible.
   *
   * Unit:
   * kWh_th
   */
  minimumReserveEnergy: number;

  planningHorizonHours: number;

  timeStepHours: number;

  householdReservePower: number;

  targetTemperature: number;

  /*
   * Optional process-wide causal accelerator.
   *
   * When supplied, the complete causal Waterline correction is
   * delegated to the global acceleration scope in ONE call.
   *
   * When absent, the original TypeScript implementation below remains
   * the numerical reference/fallback.
   */
  causalAccelerator?:
    PeakShavingCausalAccelerator;
}


/*
 * ==================================================================
 * SCHEDULER RESULT
 * ==================================================================
 */
export interface PlasmaWavePeakShavingScheduleResult {

  cop: number;

  maximumHeatPumpElectricalPower: number;

  targetStorageEnergy: number;

  availableStorageCapacity: number;

  requestedChargeThermalEnergy: number;

  scheduledChargeThermalEnergy: number;

  unscheduledChargeThermalEnergy: number;

  scheduledHeatPumpElectricalEnergy: number;

  /*
   * Final causal Waterline.
   *
   * Unit:
   * kW_el
   */
  cutLevelPower: number;

  currentScheduledHeatPumpElectricalPower: number;

  currentScheduledHeatPumpThermalPower: number;

  schedule: PlasmaWavePeakShavingSchedulePoint[];
}


/*
 * ==================================================================
 * INTERNAL FORECAST BUCKET
 * ==================================================================
 *
 * This is where the time dimension is retained.
 *
 * The old scheduler only needed:
 *
 *   PV export
 *
 * The new scheduler also keeps:
 *
 *   future demand for THIS 15-minute position
 *
 * Cooling is calculated dynamically because cooling depends on
 * the simulated tank energy and therefore cannot be represented
 * correctly by one fixed scalar.
 */
interface ForecastBucket {

  timestamp: string;

  pvPower: number;

  exportPower: number;

  demandEnergy: number;
}


/*
 * ==================================================================
 * PERFORMANCE PROFILER
 * ==================================================================
 *
 * Diagnostic copy of the normal peak-shaving scheduler.
 * Controller logic is unchanged; only timing counters are added.
 *
 * The profile resets automatically at currentIndex === 0 and is
 * printed after the final annual index.
 */
interface PeakShavingPerformanceProfile {
  calls: number;

  totalMs: number;
  bucketBuildMs: number;
  energySearchMs: number;
  causalSearchMs: number;
  scheduleMaterializationMs: number;

  energyBinarySearchIterations: number;
  causalSurvivalChecks: number;
  causalBinarySearchIterations: number;
}


const performanceProfile:
  PeakShavingPerformanceProfile = {

  calls: 0,

  totalMs: 0,
  bucketBuildMs: 0,
  energySearchMs: 0,
  causalSearchMs: 0,
  scheduleMaterializationMs: 0,

  energyBinarySearchIterations: 0,
  causalSurvivalChecks: 0,
  causalBinarySearchIterations: 0,
};


function resetPerformanceProfile():
  void {

  performanceProfile.calls = 0;

  performanceProfile.totalMs = 0;
  performanceProfile.bucketBuildMs = 0;
  performanceProfile.energySearchMs = 0;
  performanceProfile.causalSearchMs = 0;
  performanceProfile.scheduleMaterializationMs = 0;

  performanceProfile.energyBinarySearchIterations = 0;
  performanceProfile.causalSurvivalChecks = 0;
  performanceProfile.causalBinarySearchIterations = 0;
}


function printPerformanceProfile():
  void {

  const measuredSectionsMs =
    performanceProfile.bucketBuildMs +
    performanceProfile.energySearchMs +
    performanceProfile.causalSearchMs +
    performanceProfile.scheduleMaterializationMs;

  const otherMs = Math.max(
    0,
    performanceProfile.totalMs - measuredSectionsMs,
  );

  const percent =
    (value: number): string =>
      performanceProfile.totalMs > 0
        ? (
            value /
            performanceProfile.totalMs *
            100
          ).toFixed(1)
        : "0.0";


  console.info(
    "[SunOpt] 48h peak-shaving performance profile:",
    {
      calls:
        performanceProfile.calls,

      totalMs:
        performanceProfile.totalMs.toFixed(1),

      bucketBuildMs:
        performanceProfile.bucketBuildMs.toFixed(1),

      bucketBuildPercent:
        percent(performanceProfile.bucketBuildMs),

      energySearchMs:
        performanceProfile.energySearchMs.toFixed(1),

      energySearchPercent:
        percent(performanceProfile.energySearchMs),

      causalSearchMs:
        performanceProfile.causalSearchMs.toFixed(1),

      causalSearchPercent:
        percent(performanceProfile.causalSearchMs),

      scheduleMaterializationMs:
        performanceProfile.scheduleMaterializationMs.toFixed(1),

      scheduleMaterializationPercent:
        percent(
          performanceProfile.scheduleMaterializationMs,
        ),

      otherMs:
        otherMs.toFixed(1),

      otherPercent:
        percent(otherMs),

      energyBinarySearchIterations:
        performanceProfile.energyBinarySearchIterations,

      causalSurvivalChecks:
        performanceProfile.causalSurvivalChecks,

      causalBinarySearchIterations:
        performanceProfile.causalBinarySearchIterations,
    },
  );
}


/*
 * ==================================================================
 * WRAP INDEX
 * ==================================================================
 *
 * Allows a 48 h forecast near 31 December to continue into the
 * beginning of the annual arrays.
 */
function wrapIndex(
  index: number,
  length: number,
): number {

  return ((index % length) + length) % length;
}


/*
 * ==================================================================
 * MAIN WATERLINE SCHEDULER
 * ==================================================================
 */
export function calculatePlasmaWavePeakShavingSchedule(
  input: PlasmaWavePeakShavingScheduleInput,
): PlasmaWavePeakShavingScheduleResult {

  const {
    weatherData,
    heatPump,
    storage,
    currentIndex,
    currentStorageEnergy,
    requiredThermalInventory,
    historicalSeries,
    minimumReserveEnergy,
    planningHorizonHours,
    targetTemperature,
    causalAccelerator,
  } = input;

  const timeStepHours =
  historicalSeries.timeStepHours;


  const householdReservePower =
  historicalSeries.householdReservePower;

  if (currentIndex === 0) {
    resetPerformanceProfile();
  }


  const profileCallStart =
    performance.now();


  /*
   * =================================================================
   * 0. VALIDATION
   * =================================================================
   */

  if (weatherData.length === 0) {
    throw new Error(
      "weatherData must not be empty.",
    );
  }

  if (
    currentIndex < 0 ||
    currentIndex >= weatherData.length
  ) {
    throw new Error(
      "currentIndex is outside weatherData.",
    );
  }

  if (
    historicalSeries.length !==
    weatherData.length
  ) {
    throw new Error(
      "Historical series and weather data must have same length.",
    );
  }

  if (planningHorizonHours <= 0) {
    throw new Error(
      "planningHorizonHours must be greater than zero.",
    );
  }

  if (timeStepHours <= 0) {
    throw new Error(
      "timeStepHours must be greater than zero.",
    );
  }

  if (householdReservePower < 0) {
    throw new Error(
      "householdReservePower cannot be negative.",
    );
  }

  if (minimumReserveEnergy < 0) {
    throw new Error(
      "minimumReserveEnergy cannot be negative.",
    );
  }


  /*
   * =================================================================
   * 1. COP AND MAXIMUM HP POWER
   * =================================================================
   *
   * The Waterline itself operates on electrical PV power.
   *
   * The heat pump is defined by thermal power.
   *
   * Therefore:
   *
   *   P_HP,el,max = P_HP,th,max / COP
   */

  const referenceHeatPumpStep =
    calculateHeatPumpStep(
      heatPump,
      heatPump.thermalPower * timeStepHours,
      timeStepHours,
    );

  const cop = referenceHeatPumpStep.cop;

  if (cop <= 0) {
    throw new Error(
      "Heat-pump COP must be greater than zero.",
    );
  }

  const maximumHeatPumpElectricalPower =
    heatPump.thermalPower / cop;


  /*
   * =================================================================
   * 2. PHYSICAL STORAGE LIMIT
   * =================================================================
   *
   * The tank cannot be charged beyond the lowest of:
   *
   * - requested target
   * - tank maximum temperature
   * - HP maximum flow temperature
   */

  const physicallyReachableTargetTemperature =
    Math.min(
      targetTemperature,
      storage.maxTemperature,
      heatPump.maxFlowTemperature,
    );

  const targetStorageEnergy =
    calculateStorageEnergyAtTemperature(
      storage,
      physicallyReachableTargetTemperature,
    );

  const clampedCurrentStorageEnergy =
    Math.min(
      targetStorageEnergy,
      Math.max(0, currentStorageEnergy),
    );

  const availableStorageCapacity =
    Math.max(
      0,
      targetStorageEnergy -
        clampedCurrentStorageEnergy,
    );


  /*
   * The reserve itself can never be larger than the tank target.
   *
   * This is mainly defensive programming.
   */
  const reserveFloorEnergy =
    Math.min(
      targetStorageEnergy,
      minimumReserveEnergy,
    );


  /*
   * =================================================================
   * 3. TOTAL 48 h ENERGY TARGET
   * =================================================================
   *
   * We KEEP the original total-energy logic.
   *
   * This gives the normal peak-shaving Waterline.
   *
   * The new chronological calculation later checks whether that
   * Waterline also supplies the energy early enough.
   */

  const missingToRequiredInventory =
    Math.max(
      0,
      requiredThermalInventory -
        clampedCurrentStorageEnergy,
    );

  const requestedChargeThermalEnergy =
    Math.min(
      missingToRequiredInventory,
      availableStorageCapacity,
    );


  /*
   * =================================================================
   * 4. BUILD ALL 192 FUTURE BUCKETS
   * =================================================================
   *
   * This is the important conceptual change.
   *
   * We do NOT merely create one 48 h PV integral.
   *
   * Every future 15-minute interval remains a distinct bucket:
   *
   *   bucket 0   = now
   *   bucket 1   = now + 15 min
   *   bucket 2   = now + 30 min
   *   ...
   *   bucket 191 = almost 48 h ahead
   *
   * Each bucket contains:
   *
   * - its PV export
   * - its forecast DHW demand
   *
   * Cooling is calculated later while the simulated tank advances
   * through these buckets.
   */

  const bucketBuildStart =
    performance.now();


  const forecastSteps =
    Math.min(
      Math.ceil(
        planningHorizonHours / timeStepHours,
      ),
      weatherData.length,
    );

  const buckets: ForecastBucket[] = [];

  let maximumExportPower = 0;

  for (
    let offset = 0;
    offset < forecastSteps;
    offset++
  ) {

    const index =
      wrapIndex(
        currentIndex + offset,
        weatherData.length,
      );

    const weatherPoint = weatherData[index];

    if (!weatherPoint) {
      throw new Error(
        `Weather point missing at index ${index}.`,
      );
    }

    const demandEnergy =
    historicalSeries
      .loadEnergyByIndex[index] ?? 0;
  
  
  const exportPower =
    historicalSeries
      .exportPowerByIndex[index] ?? 0;

    maximumExportPower =
      Math.max(
        maximumExportPower,
        exportPower,
      );

    buckets.push({
      timestamp: weatherPoint.timestamp,
      pvPower: weatherPoint.pvPower,
      exportPower,
      demandEnergy: Math.max(0, demandEnergy),
    });
  }


  performanceProfile.bucketBuildMs +=
    performance.now() - bucketBuildStart;


  /*
   * =================================================================
   * 5. HP POWER FOR ONE WATERLINE
   * =================================================================
   *
   * Same Plasma-Wave equation as before:
   *
   *   P_HP =
   *     min(
   *       P_HP,max,
   *       max(0, P_export - Waterline)
   *     )
   *
   * Lower Waterline:
   *   more PV is used.
   *
   * Higher Waterline:
   *   only the highest PV peaks are used.
   */

  function hpPowerAtCutLevel(
    exportPower: number,
    cutLevelPower: number,
  ): number {

    const powerAboveWaterline =
      Math.max(
        0,
        exportPower - cutLevelPower,
      );

    return Math.min(
      maximumHeatPumpElectricalPower,
      powerAboveWaterline,
    );
  }


  /*
   * =================================================================
   * 6. OLD TOTAL-ENERGY TEST
   * =================================================================
   *
   * We intentionally retain this function.
   *
   * It answers:
   *
   *   "How much total electrical energy would this Waterline
   *    schedule across the complete 48 h?"
   *
   * This is useful for choosing the economically attractive
   * peak-shaving level.
   *
   * It is NOT sufficient on its own because it ignores WHEN the
   * scheduled energy arrives.
   */

  function electricalEnergyAtCutLevel(
    cutLevelPower: number,
  ): number {

    let electricalEnergy = 0;

    for (const bucket of buckets) {

      const hpPower =
        hpPowerAtCutLevel(
          bucket.exportPower,
          cutLevelPower,
        );

      electricalEnergy +=
        hpPower * timeStepHours;
    }

    return electricalEnergy;
  }


  /*
   * =================================================================
   * 7. CHRONOLOGICAL / CAUSAL WATERLINE TEST
   * =================================================================
   *
   * THIS fixes the bug we found.
   *
   * The old calculation treated:
   *
   *   energy on 15 July
   *
   * and:
   *
   *   energy on 17 July
   *
   * as interchangeable parts of the same 48 h integral.
   *
   * They are NOT interchangeable.
   *
   * Demand on 16 July cannot be supplied retroactively by sunshine
   * arriving on 17 July.
   *
   *
   * We therefore simulate the forecast in chronological order.
   *
   * For every future quarter hour:
   *
   *   1. cool the tank
   *   2. remove that quarter-hour DHW bucket
   *   3. check whether reserve has been violated
   *   4. add forecast HP charging for that quarter hour
   *
   *
   * Notice the order.
   *
   * The common physical simulation checks demand / reserve before
   * forecast charging.
   *
   * Therefore a Waterline charge occurring in a future quarter-hour
   * is too late if the tank had already crossed reserve at the start
   * of that quarter-hour.
   *
   *
   * OFFSET ZERO
   * -----------
   *
   * currentStorageEnergy is already the controller's present storage
   * state AFTER the current physical demand/loss preview.
   *
   * Therefore bucket 0 must NOT subtract current demand or cooling
   * a second time.
   *
   * We only apply the Waterline charge belonging to NOW.
   *
   *
   * RETURN VALUE
   * ------------
   *
   * true:
   *   this Waterline survives all future buckets without requiring
   *   mandatory reserve/grid intervention.
   *
   * false:
   *   at least one future bucket becomes short before later PV can
   *   rescue it.
   */

  function survivesAtCutLevel(
    cutLevelPower: number,
  ): boolean {

    performanceProfile.causalSurvivalChecks += 1;


    let simulatedEnergy =
      clampedCurrentStorageEnergy;

    for (
      let offset = 0;
      offset < buckets.length;
      offset++
    ) {

      const bucket = buckets[offset];

      if (!bucket) {
        continue;
      }

      const hpPower =
        hpPowerAtCutLevel(
          bucket.exportPower,
          cutLevelPower,
        );

      const hpThermalEnergy =
        hpPower * cop * timeStepHours;


      /*
       * -------------------------------------------------------------
       * CURRENT BUCKET
       * -------------------------------------------------------------
       *
       * Demand and cooling for NOW have already happened before
       * Plasma Wave receives currentStorageEnergy.
       *
       * Do not count them twice.
       */
      if (offset === 0) {

        simulatedEnergy =
          Math.min(
            targetStorageEnergy,
            simulatedEnergy +
              hpThermalEnergy,
          );

        continue;
      }


      /*
       * -------------------------------------------------------------
       * FUTURE DEMAND + COOLING BUCKET
       * -------------------------------------------------------------
       *
       * The canonical storage function calculates exactly one
       * physical 15-minute interval:
       *
       *   passive cooling
       *   +
       *   future DHW withdrawal
       *
       * No forecast HP energy is passed into it here because we need
       * to inspect the tank state BEFORE forecast charging.
       *
       * This is exactly the point at which the common controller
       * would otherwise start mandatory reserve charging.
       */
      const storageStep =
        calculateThermalStorageStep({
          storage,
          currentEnergy: simulatedEnergy,
          thermalInputEnergy: 0,
          thermalOutputEnergy:
            bucket.demandEnergy,
          timeStepHours,
        });

      const energyBeforeForecastCharge =
        storageStep.state.storedEnergy;


      /*
       * If actual demand could not be supplied from stored energy,
       * the Waterline was definitely too high.
       *
       * A later sunshine cannot repair this earlier deficit.
       */
      if (storageStep.unmetDemand > 0.000001) {
        return false;
      }


      /*
       * If this state is below the mandatory reserve threshold,
       * the common controller would intervene here.
       *
       * In summer, when sufficient earlier PV exists, this is the
       * consequential behaviour we want Plasma Wave to prevent.
       */
      const reserveError =
        reserveFloorEnergy -
        energyBeforeForecastCharge;

      if (reserveError > 0.000001) {
        return false;
      }


      /*
       * -------------------------------------------------------------
       * APPLY THIS FUTURE WATERLINE CHARGE
       * -------------------------------------------------------------
       *
       * Only now do we add the HP energy assigned to this future
       * quarter hour.
       *
       * The tank target provides the physical upper limit.
       */
      simulatedEnergy =
        Math.min(
          targetStorageEnergy,
          energyBeforeForecastCharge +
            hpThermalEnergy,
        );
    }


    /*
     * Every demand/cooling bucket survived in chronological order.
     */
    return true;
  }


  /*
   * =================================================================
   * 8. NORMAL ENERGY WATERLINE
   * =================================================================
   *
   * First calculate the Waterline exactly as before.
   *
   * This produces the highest useful PV peaks first and schedules
   * the desired total 48 h energy.
   */

  const energySearchStart =
    performance.now();


  const requestedElectricalEnergy =
    requestedChargeThermalEnergy / cop;

  const maximumSchedulableElectricalEnergy =
    electricalEnergyAtCutLevel(0);

  const targetElectricalEnergy =
    Math.min(
      requestedElectricalEnergy,
      maximumSchedulableElectricalEnergy,
    );

  let energyCutLevel = maximumExportPower;

  if (
    targetElectricalEnergy > 0 &&
    maximumExportPower > 0
  ) {

    if (
      targetElectricalEnergy >=
      maximumSchedulableElectricalEnergy
    ) {

      energyCutLevel = 0;

    } else {

      let lowerCut = 0;
      let upperCut = maximumExportPower;

      /*
       * This is the original monotonic energy search.
       *
       * A lower cut schedules MORE total energy.
       * A higher cut schedules LESS total energy.
       */
      for (
        let iteration = 0;
        iteration < 32;
        iteration++
      ) {

        performanceProfile
          .energyBinarySearchIterations += 1;


        const middleCut =
          (lowerCut + upperCut) / 2;

        const energyAtMiddle =
          electricalEnergyAtCutLevel(
            middleCut,
          );

        if (
          energyAtMiddle >
          targetElectricalEnergy
        ) {

          lowerCut = middleCut;

        } else {

          upperCut = middleCut;
        }
      }

      energyCutLevel =
        (lowerCut + upperCut) / 2;
    }
  }


  performanceProfile.energySearchMs +=
    performance.now() - energySearchStart;


  /*
   * =================================================================
   * 9. CAUSAL WATERLINE CORRECTION
   * =================================================================
   *
   * Now ask the question the old scheduler never asked:
   *
   *   "Does the normal Waterline deliver its energy soon enough?"
   *
   *
   * CASE A
   * ------
   *
   * Normal Waterline survives all buckets.
   *
   * Keep it unchanged.
   *
   *
   * CASE B
   * ------
   *
   * Normal Waterline fails, but Waterline 0 survives.
   *
   * There IS enough earlier PV.
   *
   * Therefore find the highest Waterline that still survives.
   *
   * This is the important July case.
   *
   *
   * CASE C
   * ------
   *
   * Even Waterline 0 fails.
   *
   * There simply is not enough forecast PV before the demand arrives.
   *
   * Use every available PV interval by selecting Waterline 0.
   *
   * Later mandatory/grid charging is then correct and unavoidable.
   * This is the intended winter behaviour.
   */

  const causalSearchStart =
    performance.now();


  let cutLevelPower =
    energyCutLevel;


  if (
    causalAccelerator !==
    undefined
  ) {

    /*
     * =============================================================
     * GLOBAL ACCELERATED CAUSAL SEARCH
     * =============================================================
     *
     * One accelerator call performs:
     *
     * - normal Waterline survival test
     * - Waterline 0 survival test when required
     * - complete 20-iteration causal binary search when required
     *
     * This avoids crossing the JavaScript/native boundary for every
     * individual survivesAtCutLevel() call.
     */
    const causalResult =
      causalAccelerator.run({

        currentIndex,

        horizonSteps:
          buckets.length,

        currentStorageEnergy:
          clampedCurrentStorageEnergy,

        minimumReserveEnergy:
          reserveFloorEnergy,

        targetStorageEnergy,

        maximumHeatPumpElectricalPower,

        cop,

        energyCutLevel,
      });


    cutLevelPower =
      causalResult.cutLevelPower;


    performanceProfile
      .causalSurvivalChecks +=
      causalResult
        .survivalChecks;


    performanceProfile
      .causalBinarySearchIterations +=
      causalResult
        .binarySearchIterations;

  } else {

    /*
     * =============================================================
     * ORIGINAL TYPESCRIPT REFERENCE
     * =============================================================
     *
     * Kept intact as the verification/fallback implementation.
     */
    const normalPlanSurvives =
      survivesAtCutLevel(
        energyCutLevel,
      );


    if (
      !normalPlanSurvives
    ) {

      const maximumPvPlanSurvives =
        survivesAtCutLevel(
          0,
        );


      if (
        !maximumPvPlanSurvives
      ) {

        cutLevelPower =
          0;

      } else {

        let lowerCut =
          0;

        let upperCut =
          energyCutLevel;


        for (
          let iteration = 0;
          iteration < 20;
          iteration++
        ) {

          performanceProfile
            .causalBinarySearchIterations +=
            1;


          const middleCut =
            (
              lowerCut +
              upperCut
            ) /
            2;


          if (
            survivesAtCutLevel(
              middleCut,
            )
          ) {

            lowerCut =
              middleCut;

          } else {

            upperCut =
              middleCut;
          }
        }


        cutLevelPower =
          lowerCut;
      }
    }
  }


  performanceProfile.causalSearchMs +=
    performance.now() -
    causalSearchStart;


  /*
   * =================================================================
   * 10. MATERIALISE THE FINAL 48 h SCHEDULE
   * =================================================================
   *
   * IMPORTANT:
   *
   * The causal correction can result in more theoretical 48 h
   * scheduled energy than requestedChargeThermalEnergy.
   *
   * That is intentional.
   *
   * Why?
   *
   * Because the controller never executes this complete theoretical
   * schedule.
   *
   * It executes ONLY schedule[0].
   *
   * Fifteen minutes later:
   *
   * - the tank contains the energy actually charged
   * - the horizon moves forward
   * - required inventory is recalculated
   * - Waterline is recalculated
   *
   * Therefore energy theoretically assigned to 17 July today does
   * not blindly remain assigned there.
   *
   * When that future sunshine becomes nearer, the whole optimisation
   * is solved again from the new present.
   */

  const scheduleMaterializationStart =
    performance.now();


  const schedule:
    PlasmaWavePeakShavingSchedulePoint[] = [];

  let scheduledHeatPumpElectricalEnergy = 0;

  for (const bucket of buckets) {

    const scheduledHeatPumpElectricalPower =
      hpPowerAtCutLevel(
        bucket.exportPower,
        cutLevelPower,
      );

    const scheduledHeatPumpThermalPower =
      scheduledHeatPumpElectricalPower * cop;

    scheduledHeatPumpElectricalEnergy +=
      scheduledHeatPumpElectricalPower *
      timeStepHours;

    const exportPowerAfterHeatPump =
      Math.max(
        0,
        bucket.exportPower -
          scheduledHeatPumpElectricalPower,
      );

    schedule.push({
      timestamp: bucket.timestamp,
      pvPower: bucket.pvPower,
      exportPowerBeforeHeatPump:
        bucket.exportPower,
      scheduledHeatPumpElectricalPower,
      scheduledHeatPumpThermalPower,
      exportPowerAfterHeatPump,
    });
  }


  performanceProfile.scheduleMaterializationMs +=
    performance.now() - scheduleMaterializationStart;


  /*
   * =================================================================
   * 11. FINAL ENERGY BALANCE
   * =================================================================
   */

  const scheduledChargeThermalEnergy =
    scheduledHeatPumpElectricalEnergy * cop;

  const unscheduledChargeThermalEnergy =
    Math.max(
      0,
      requestedChargeThermalEnergy -
        scheduledChargeThermalEnergy,
    );


  /*
   * =================================================================
   * 12. CURRENT STEP
   * =================================================================
   *
   * This is the only point actually sent to the physical simulation.
   */

  const currentSchedulePoint = schedule[0];


  /*
   * =================================================================
   * RESULT
   * =================================================================
   */

  const result:
    PlasmaWavePeakShavingScheduleResult = {
    cop,
    maximumHeatPumpElectricalPower,
    targetStorageEnergy,
    availableStorageCapacity,
    requestedChargeThermalEnergy,
    scheduledChargeThermalEnergy,
    unscheduledChargeThermalEnergy,
    scheduledHeatPumpElectricalEnergy,
    cutLevelPower,

    currentScheduledHeatPumpElectricalPower:
      currentSchedulePoint
        ?.scheduledHeatPumpElectricalPower ??
      0,

    currentScheduledHeatPumpThermalPower:
      currentSchedulePoint
        ?.scheduledHeatPumpThermalPower ??
      0,

    schedule,
  };


  performanceProfile.calls += 1;

  performanceProfile.totalMs +=
    performance.now() - profileCallStart;


  if (
    currentIndex ===
    weatherData.length - 1
  ) {
    printPerformanceProfile();
  }


  return result;
}